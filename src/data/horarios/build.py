def save(filename, linea, sentido, horarios):
    data = {
        "linea": linea,
        "sentido": sentido,
        "actualizado": ACTUALIZADO,
        "horarios": [{"hora": h, "recorrido": r} for h, r in horarios],
    }
    path = os.path.join(OUT_DIR, filename)
    with open(path, "w", encoding="utf-8") as f:
        json.dump(data, f, ensure_ascii=False, indent=2)
    print(f"OK {filename} ({len(horarios)} horarios)")


